export function candidatesFromEntityFile(
  doc: Document,
  tag: string,
  surface: string,
  origin: 'pedb' | 'cedb' = 'pedb',
): DisambiguationCandidate[] {
  const kind = tag === 'name' ? 'person' : TAG_TO_KIND[tag];
  if (!kind) return [];

  const nameTag = ENTITY_KINDS[kind].name;
  const items = entityElements(doc, kind);
  const out: DisambiguationCandidate[] = [];
  for (let i = 0; i < items.length; i++) {
    const el = items[i]!;
    if (!entityNameMatches(el, nameTag, surface)) continue;
    const localId = el.getAttribute('xml:id') ?? '';
    const idnos = Array.from(el.getElementsByTagName('idno'));
    const authorityIds: AuthorityId[] = idnos.map((idno) => ({
      type: idno.getAttribute('type') ?? 'unknown',
      value: idno.textContent?.trim() ?? '',
    }));
    const notes = Array.from(el.getElementsByTagName('note'));
    const descriptionNote =
      notes.find((note) => note.getAttribute('type') === 'description') ??
      notes.find((note) => !note.getAttribute('type'));
    let startYear =
      parseIsoYear(el.getElementsByTagName('birth')[0]?.getAttribute('when')) ?? undefined;
    let endYear =
      parseIsoYear(el.getElementsByTagName('death')[0]?.getAttribute('when')) ?? undefined;
    const datesNote = notes.find((note) => note.getAttribute('type') === 'dates');
    if (startYear == null && endYear == null && datesNote) {
      const [start, end] = (datesNote.textContent ?? '').split('/');
      startYear = parseIsoYear(start) ?? undefined;
      endYear = parseIsoYear(end) ?? undefined;
    }
    const nameEls = entityNameElements(el, nameTag);
    const nameTexts = nameEls.map((name) => textWithoutHiddenReadings(name).trim()).filter(Boolean);
    const romanizedNameEl = nameEls.find((name) => isLatnLang(name.getAttribute('xml:lang')));
    const romanizedName = romanizedNameEl
      ? textWithoutHiddenReadings(romanizedNameEl).trim()
      : undefined;
    out.push({
      id: localId || `local-${i}`,
      label: nameTexts[0] || surface,
      description: descriptionNote?.textContent ?? undefined,
      sources: origin === 'cedb' ? ['central-database'] : ['entity-file'],
      localEntityId: origin === 'pedb' ? localId || undefined : undefined,
      centralEntityId: origin === 'cedb' ? localId || undefined : undefined,
      authorityIds,
      fromEntityFile: true,
      startYear,
      endYear,
      projectLangName: nameTexts.find((text) => !isLatinSurface(text)),
      romanizedName: romanizedName || undefined,
    });
  }
  return out;
}

/** Minimal entity snapshot for building disambiguation candidates from SQLite. */
export interface SqliteDisambiguationEntityInput {
  id: string;
  label: string;
  description?: string | null;
  authorities?: AuthorityId[];
  names: { text: string; language?: string | null }[];
  startYear?: number | null;
  endYear?: number | null;
}

/**
 * Same surface-matching behaviour as `candidatesFromEntityFile`, but from typed
 * SQLite rows (search + panel summary) instead of a full XML export.
 */
export function candidatesFromSqliteEntities(
  entities: readonly SqliteDisambiguationEntityInput[],
  surface: string,
  origin: 'pedb' | 'cedb' = 'pedb',
): DisambiguationCandidate[] {
  const out: DisambiguationCandidate[] = [];
  for (const entity of entities) {
    const nameTexts = entity.names.map((name) => name.text.trim()).filter(Boolean);
    if (!nameTexts.some((text) => stringsMatchExactly(surface, text))) continue;
    const romanizedName = entity.names
      .find((name) => isLatnLang(name.language ?? null))
      ?.text.trim();
    out.push({
      id: entity.id,
      label: entity.label || nameTexts[0] || surface,
      description: entity.description ?? undefined,
      sources: origin === 'cedb' ? ['central-database'] : ['entity-file'],
      localEntityId: origin === 'pedb' ? entity.id : undefined,
      centralEntityId: origin === 'cedb' ? entity.id : undefined,
      authorityIds: entity.authorities ?? [],
      fromEntityFile: true,
      startYear: entity.startYear ?? undefined,
      endYear: entity.endYear ?? undefined,
      projectLangName: nameTexts.find((text) => !isLatinSurface(text)),
      romanizedName: romanizedName || undefined,
    });
  }
  return out;
}

/** Provenance keys that mean "from this user's entity database" (PEDB or CEDB). */
const OWN_DATABASE_SOURCES = new Set(['entity-file', 'central-database', 'pedb', 'cedb']);

export function isOwnDatabaseSource(source: string): boolean {
  return OWN_DATABASE_SOURCES.has(source.trim().toLowerCase());
}

/**
 * Collapse Local/Central provenance labels to a single "central-database" for
 * synced projects, where every entity lives in the central database and the
 * Local/Central split is meaningless — but the entity is still, correctly,
 * from the user's own database rather than a bare external authority hit.
 */
export function centralizeOwnDatabaseSources(sources: string[]): string[] {
  let sawOwnDatabase = false;
  const rest = sources.filter((source) => {
    if (isOwnDatabaseSource(source)) {
      sawOwnDatabase = true;
      return false;
    }
    return true;
  });
  return sawOwnDatabase ? ['central-database', ...rest] : rest;
}

/**
 * Rewrite an entity-database candidate for a syncToCentral project: collapse
 * Local/Central source labels to "central-database", and when a PEDB mirror
 * id is known prefer that so "already in document" / accept paths use the
 * project key.
 */
export function asSyncedEntityCandidate(
  candidate: DisambiguationCandidate,
  linkedPedbId?: string | null,
): DisambiguationCandidate {
  const pedbId = linkedPedbId?.trim() || undefined;
  return {
    ...candidate,
    sources: centralizeOwnDatabaseSources(candidate.sources),
    localEntityId: pedbId ?? candidate.localEntityId,
    centralEntityId: pedbId ? undefined : candidate.centralEntityId,
  };
}

/** How many same-surface PEDB/CEDB hits disambiguation will load from SQLite. */
const SQLITE_DISAMBIGUATION_SEARCH_LIMIT = 200;

/**
 * Load surface-matching disambiguation candidates from a migrated SQLite store.
 * Returns null when SQLite search is unavailable — callers must fail loud,
 * not fall back to XML/`loadEntities`.
 */
export async function loadSqliteDisambiguationCandidates(
  store: EntityStore,
  tag: string,
  surface: string,
  origin: 'pedb' | 'cedb' = 'pedb',
): Promise<DisambiguationCandidate[] | null> {
  const kind = tag === 'name' ? 'person' : TAG_TO_KIND[tag];
  if (!kind) return [];
  const hits = await store.sqliteSearchNames(kind, surface, SQLITE_DISAMBIGUATION_SEARCH_LIMIT);
  if (hits == null) return null;

  const entities: SqliteDisambiguationEntityInput[] = [];
  for (const hit of hits) {
    const summary = (await store.sqliteEntitySummary(hit.id)) as {
      id?: string;
      description?: string | null;
      authorities?: AuthorityId[];
      names?: { text: string; language?: string | null; status?: string }[];
      startYear?: number | null;
      endYear?: number | null;
    } | null;
    if (!summary) continue;
    const names = (summary.names ?? [])
      .filter((name) => name.status !== 'rejected' && name.status !== 'withdrawn')
      .map((name) => ({ text: name.text, language: name.language ?? null }));
    entities.push({
      id: summary.id ?? hit.id,
      label: hit.label,
      description: summary.description ?? hit.description ?? null,
      authorities: summary.authorities ?? hit.idnos,
      names: names.length > 0 ? names : [{ text: hit.label, language: null }],
      startYear: summary.startYear ?? null,
      endYear: summary.endYear ?? null,
    });
  }
  return candidatesFromSqliteEntities(entities, surface, origin);
}

function mergeIntoExisting(
  existing: DisambiguationCandidate,
  candidate: DisambiguationCandidate,
): void {
  existing.sources = Array.from(new Set([...existing.sources, ...candidate.sources]));
  if (candidate.authorityIds) {
    existing.authorityIds = [...(existing.authorityIds ?? []), ...candidate.authorityIds];
  }
  existing.geo ??= candidate.geo;
}

export function mergeCandidates(
  lists: DisambiguationCandidate[][],
  options?: MergeCandidateOptions,
): DisambiguationCandidate[] {
  const byLocal = new Map<string, DisambiguationCandidate>();
  const byCentral = new Map<string, DisambiguationCandidate>();
  const out: DisambiguationCandidate[] = [];

  for (const list of lists) {
    for (const candidate of list.flatMap((item) =>
      item.authorityAssertions?.length ? [item, ...item.authorityAssertions] : [item],
    )) {
      if (candidate.localEntityId) {
        const existing = byLocal.get(candidate.localEntityId);
        if (existing) {
          mergeIntoExisting(existing, candidate);
          continue;
        }
        byLocal.set(candidate.localEntityId, candidate);
        out.push(candidate);
        continue;
      }

      if (candidate.centralEntityId) {
        const existing = byCentral.get(candidate.centralEntityId);
        if (existing) {
          mergeIntoExisting(existing, candidate);
          continue;
        }
        byCentral.set(candidate.centralEntityId, candidate);
        out.push(candidate);
        continue;
      }

      const dup = out.find((c) => c.uri && c.uri === candidate.uri);
      if (dup) {
        mergeIntoExisting(dup, candidate);
        continue;
      }
      out.push(candidate);
    }
  }
  return collapseCrossAuthorityCandidates(out.map(enrichCandidateCrossRefs), options);
}

/** Session-lifetime cache of Wikidata Q-id → lifespan (or null when none found). */
const wikidataLifespanCache = new Map<string, Awaited<ReturnType<typeof fetchWikidataLifespan>>>();

/** Drop Wikidata reconcile rows whose Q-id is not the expected entity kind. */
async function filterWikidataByKind<T extends { uri: string; description?: string }>(
  matches: T[],
  kind: EntityKind,
  cache: AuthorityCache,
): Promise<T[]> {
  if (matches.length === 0) return matches;

  const withQid: { match: T; qid: string }[] = [];
  for (const match of matches) {
    const qid = extractWikidataId(match.uri) ?? extractWikidataId(match.description ?? '');
    if (qid) withQid.push({ match, qid });
  }
  if (withQid.length === 0) return [];

  const qids = [...new Set(withQid.map((row) => row.qid))];
  await cache.throttle();
  const matching =
    kind === 'thing'
      ? await wikidataQidsExcludingKnownKinds(qids)
      : await wikidataQidsMatchingKind(qids, kind);
  return withQid.filter((row) => matching.has(row.qid)).map((row) => row.match);
}

