/** Session-lifetime cache of parsed CHGIS rows, keyed by exact search string. */
let chgisIndexPromise: Promise<Map<string, { startYear?: number; endYear?: number }>> | null = null;

function buildChgisIndex(
  rows: AuthorityCandidate[],
): Map<string, { startYear?: number; endYear?: number }> {
  const index = new Map<string, { startYear?: number; endYear?: number }>();
  for (const row of rows) {
    const years = { startYear: row.metadata?.startYear, endYear: row.metadata?.endYear };
    if (years.startYear == null && years.endYear == null) continue;
    for (const str of row.searchStrings) {
      if (!index.has(str)) index.set(str, years);
    }
  }
  return index;
}

/** Look up begin/end years for a place surface string in the installed CHGIS pack (cached for the session). */
async function chgisYearsForSurface(
  surface: string,
  readPackFile: ReadAuthorityPackFile,
): Promise<{ startYear?: number; endYear?: number } | null> {
  chgisIndexPromise ??= (async () => {
    try {
      const content = await readPackFile('chgis-places');
      return buildChgisIndex(parseAuthorityNdjson(content));
    } catch {
      return new Map();
    }
  })();
  const index = await chgisIndexPromise;
  return index.get(surface) ?? null;
}

/**
 * Fetch and cache live 備註/朝代 dates for a DILA place id in the background.
 * Local pack metadata already covers a handful of places whose remark date range
 * was extractable from the bulk XML export; this fills in the rest on demand,
 * scraping the live record page (there is no by-string search API — only by id).
 * Fire-and-forget: the disambiguation panel must not block on a live network
 * scrape just to open, so misses are queued rather than awaited inline.
 */
async function fetchAndCacheDilaPlaceDetail(
  authorityId: string,
  dilaDetailCache: DilaPlaceDetailCache,
  fetchImpl?: DilaFetchFn,
): Promise<void> {
  await dilaDetailCache.throttle();
  try {
    const detail = await fetchDilaPlaceDetail(authorityId, fetchImpl);
    // A record with neither 備註 nor 朝代 almost always means the scrape missed
    // its target (wrong URL, page markup changed) rather than a genuinely blank
    // record — don't lock that in behind the cache's long TTL, or a lookup that
    // starts failing silently stays broken for every id it ever touches.
    if (detail && (detail.remark || detail.dynasty)) {
      await dilaDetailCache.set(authorityId, detail);
    }
  } catch {
    // best-effort; the candidate stays undated until a later lookup retries
  }
}

async function candidatesFromAuthorityPacks(
  tag: string,
  surface: string,
  readPackFile: ReadAuthorityPackFile,
  dilaDetailCache?: DilaPlaceDetailCache,
  dilaFetchImpl?: DilaFetchFn,
  onDilaDatesReady?: () => void,
  projectLang?: string | null,
): Promise<DisambiguationCandidate[]> {
  const entityType = TAG_TO_ENTITY_TYPE[tag] ?? 'person';
  const packIds = packIdsForEntityType(
    [
      'cbdb-persons',
      'cbdb-places',
      'cbdb-offices',
      'dila-persons',
      'dila-places',
      'chgis-places',
      'ndl-persons',
      'ndl-places',
      'ndl-orgs',
      'ndl-works',
      'norbert-persons',
      'norbert-person-wrappers',
      'norbert-wiki-nt',
      'norbert-offices',
    ],
    entityType,
  );
  const pendingDilaFetches: Promise<void>[] = [];
  const officeGlosses =
    entityType === 'office' ? await loadHuckbotGlossIndex(readPackFile) : undefined;
  const frenchOfficeGlosses =
    entityType === 'office' ? await loadMaxiRicciGlossIndex(readPackFile) : undefined;
  // Read packs in parallel — sequential awaits made lookup feel much slower
  // than the legacy per-authority popup (which also fired searches together).
  const perPack = await Promise.all(
    packIds.map(async (packId): Promise<DisambiguationCandidate[]> => {
      try {
        const content = await readPackFile(packId);
        const spec = AUTHORITY_PACKS.find((item) => item.id === packId);
        if (!spec) return [];
        const packSource = spec.source as 'cbdb' | 'dila' | 'chgis' | 'ndl' | 'norbert';
        const results: DisambiguationCandidate[] = [];
        // searchPackRows hands back each match's parsed ndjson row, so the
        // metadata (years, dynasty, authorityId) comes straight from the ≤10
        // matched lines — no full-pack parse per lookup.
        for (const { result: match, row } of searchPackRows(
          content,
          packSource,
          entityType,
          surface,
          undefined,
          officeGlosses,
          frenchOfficeGlosses,
        )) {
          let description = match.description;
          let dateSource = row?.metadata?.dateSource;
          if (entityType === 'person' && dateSource === 'index') {
            description = scrubIndexYearFloruitClue(description);
          }
          const filterYears =
            entityType === 'person'
              ? filterYearsFromMetadata(row?.metadata)
              : {
                  startYear: row?.metadata?.startYear ?? undefined,
                  endYear: row?.metadata?.endYear ?? undefined,
                  isFine: true,
                };
          let startYear = filterYears.startYear;
          let endYear = filterYears.endYear;
          let dynasty: string | undefined;

          // A dynasty span is not a lifespan. When the years were computed from one,
          // label them `nationality` whatever the pack claimed: the Norbert person
          // pack sets no `dateSource` on any of its 16,050 rows, so trusting that
          // field let dynasty ranges reach birth/death and show on the disambiguation
          // panel as the person's own dates. With the label applied,
          // `isFilterOnlyDateSource` keeps them out of vitals and the authority
          // backfill can strip the ones earlier mints already stored.
          if (filterYears.derivedFromDynasty) dateSource = 'nationality';

          if (
            packSource === 'dila' &&
            entityType === 'place' &&
            dilaDetailCache &&
            row?.authorityId &&
            startYear == null &&
            endYear == null
          ) {
            const cached = await dilaDetailCache.get(row.authorityId);
            if (cached) {
              startYear = cached.startYear ?? startYear;
              endYear = cached.endYear ?? endYear;
              if (cached.remark) description = cached.remark;
              // DILA splits a place into one record per dynasty — lead with it so
              // same-named candidates read as distinct entries, and keep it on the
              // candidate/cache for a future dynasty filter/picker.
              if (cached.dynasty) {
                dynasty = cached.dynasty;
                description = description ? `${cached.dynasty}：${description}` : cached.dynasty;
              }
            } else {
              // Don't block opening the panel on a live scrape; queue it and
              // let the caller refresh once every queued id has resolved.
              pendingDilaFetches.push(
                fetchAndCacheDilaPlaceDetail(row.authorityId, dilaDetailCache, dilaFetchImpl),
              );
            }
          }

          results.push({
            id: match.uri,
            label: match.label,
            description,
            sources: [
              spec.source.toUpperCase(),
              ...(row?.metadata?.crosswalk?.bdrc ? ['BDRC'] : []),
            ],
            uri: match.uri,
            authorityIds: dedupeAuthorityIds(
              // The bare authorityId, not match.uri — auth.value must be an id a
              // *_URL() builder can format, not an already-fully-formed URL (which
              // would otherwise get wrapped inside another URL and break the link).
              // Norbert values are kind-prefixed (`office-4135`) so person/office
              // numeric ids cannot collide in the entity DB.
              // Pack crosswalk (incl. VIAF P214 / Wikidata Q) is first-class —
              // do not rely on scraping description text for those ids.
              authorityIdsFromCrossRefs(
                [
                  {
                    type: packSource.toUpperCase(),
                    value:
                      packSource === 'norbert' && row?.authorityId != null
                        ? formatNorbertAuthorityValue(entityType, row.authorityId)
                        : (row?.authorityId ?? match.uri),
                  },
                  ...authorityIdsFromPackCrosswalk(row?.metadata?.crosswalk, {
                    norbertKind: entityType,
                  }),
                ],
                match.description,
              ),
            ),
            startYear,
            endYear,
            dateSource:
              dateSource === 'fine' ||
              dateSource === 'floruit' ||
              dateSource === 'index' ||
              dateSource === 'nationality'
                ? dateSource
                : undefined,
            dynasty,
            projectLangName: (() => {
              const displayName = row?.displayName?.trim() || row?.primaryName;
              return displayName && !isLatinSurface(displayName) ? displayName : undefined;
            })(),
            romanizedName:
              romanizeFromAuthorityMetadata(
                row?.metadata,
                (row?.displayName?.trim() || row?.primaryName) ?? match.label,
                projectLang,
                entityType,
              ) ?? undefined,
            typedNames: typedNamesFromPackRow(row?.names),
            geo: normalizeGeo(row?.metadata?.geo),
            authorityMetadata: row?.metadata,
          });
        }
        return results;
      } catch {
        // Missing or unreadable pack; skip it.
        return [];
      }
    }),
  );
  if (pendingDilaFetches.length > 0 && onDilaDatesReady) {
    void Promise.all(pendingDilaFetches).then(onDilaDatesReady);
  }
  return perPack.flat();
}

/**
 * Same include/exclude semantics as {@link candidatePassesDateFilter}, applied to a live
 * disambiguation candidate's `startYear`/`endYear` (persons, and CHGIS-matched places).
 */
export function candidatePassesYearFilter(
  candidate: DisambiguationCandidate,
  filter?: DateRangeFilter,
): boolean {
  if (!filter || filter.mode === 'none') return true;

  const { start, end } = normalizeDateRangeFilter(filter);
  const yearStart = candidate.startYear;
  const yearEnd = candidate.endYear ?? candidate.startYear;
  const undated = yearStart == null && yearEnd == null;

  if (undated) return filter.mode === 'exclude';

  const lo = yearStart ?? yearEnd!;
  const hi = yearEnd ?? yearStart!;
  const overlaps =
    filter.mode === 'exclude'
      ? preciseDateExceedsExcludeLimit(yearStart, candidate.endYear, start)
      : lo <= end && hi >= start;
  return filter.mode === 'limit' ? overlaps : !overlaps;
}

async function lifespanForQid(qid: string, cache: AuthorityCache) {
  if (wikidataLifespanCache.has(qid)) return wikidataLifespanCache.get(qid)!;
  await cache.throttle();
  let lifespan: Awaited<ReturnType<typeof fetchWikidataLifespan>>;
  try {
    lifespan = await fetchWikidataLifespan(qid);
  } catch {
    lifespan = null;
  }
  wikidataLifespanCache.set(qid, lifespan);
  return lifespan;
}

export interface FetchLiveCandidatesOptions {
  /**
   * Fetch Wikidata birth/death years for each hit. Each call is throttled (~1s),
   * so enabling this for many QIDs is slow. Lookup dialogs should pass false;
   * the disambiguation panel keeps the default (true).
   */
  enrichLifespans?: boolean;
}

export async function fetchLiveCandidates(
  tag: string,
  surface: string,
  cache: AuthorityCache,
  enabledAuthorities: (keyof typeof AUTHORITY_MAP)[],
  forceRefresh = false,
  readPackFile?: ReadAuthorityPackFile,
  options: FetchLiveCandidatesOptions = {},
): Promise<DisambiguationCandidate[]> {
  const enrichLifespans = options.enrichLifespans !== false;
  const entityType = TAG_TO_ENTITY_TYPE[tag] ?? 'person';
  const entityKind = tag === 'name' ? 'person' : TAG_TO_KIND[tag];
  const chgisYears =
    tag === 'placeName' && readPackFile ? await chgisYearsForSurface(surface, readPackFile) : null;

  // VIAF/Getty/GND/DBpedia are Latin-heading library catalogs with no real
  // Tibetan coverage; their search fails open on a Tibetan-script query
  // (returns an arbitrary slice of the catalog — e.g. Prague and Belarus for
  // "Lhasa" — rather than no results), and those rows carry no exact-surface
  // filter the way Wikidata's do (see filterReconcileByExactSurface below).
  // Only Wikidata's reconcile results reliably echo back the queried script,
  // so it's the only authority worth querying for Tibetan-script surface text.
  const authoritiesForSurface = hasTibetan(surface)
    ? enabledAuthorities.filter((name) => name === 'Wikidata')
    : enabledAuthorities;

  // Fire Wikidata + VIAF (etc.) together, like the legacy lookup popup.
  const perAuthority = await Promise.all(
    authoritiesForSurface.map(async (name): Promise<DisambiguationCandidate[]> => {
      const authorityId = AUTHORITY_MAP[name];
      if (!authorityId) return [];

      const cached = await cache.get(name, entityType, surface, forceRefresh);
      let matches: AuthorityLookupResult[] = cached?.results ?? [];

      if (!cached) {
        await cache.throttle();
        try {
          matches = await reconcile({
            query: surface,
            entityType,
            options: { authorityId, isUserAuthenticated: false },
          });
          await cache.set({
            authority: name,
            entityType,
            query: surface,
            fetchedAt: new Date().toISOString(),
            results: matches,
          });
        } catch {
          matches = [];
        }
      }

      if (name === 'Wikidata') {
        if (entityKind) {
          matches = await filterWikidataByKind(matches, entityKind, cache);
        }
        // Exact-surface matching only makes sense against Wikidata: its reconcile rows
        // reliably return the queried script as label/alias. VIAF/DBpedia/Getty/GND
        // headings are authority-specific (often romanized, "Surname, Given, dates")
        // and rarely equal the raw surface text — filtering them the same way silently
        // dropped every non-Wikidata authority.
        matches = await filterReconcileByExactSurface(matches, surface);
      }

      const results: DisambiguationCandidate[] = [];
      for (const match of matches) {
        let description = match.description;
        let startYear: number | undefined;
        let endYear: number | undefined;
        if (enrichLifespans && entityType === 'person') {
          const qid = extractWikidataId(match.uri) ?? extractWikidataId(match.description ?? '');
          if (qid) {
            const lifespan = await lifespanForQid(qid, cache);
            description = prefixDescriptionWithLifespan(description, lifespan);
            startYear = lifespan?.birthYear;
            endYear = lifespan?.deathYear;
          }
        } else if (entityType === 'place' && chgisYears) {
          startYear = chgisYears.startYear;
          endYear = chgisYears.endYear;
        }
        results.push({
          id: match.uri,
          label: match.label,
          description,
          sources: [name],
          uri: match.uri,
          authorityIds: dedupeAuthorityIds(
            authorityIdsFromCrossRefs([{ type: name, value: match.uri }], match.description),
          ),
          startYear,
          endYear,
        });
      }
      return results;
    }),
  );

  return perAuthority.flat();
}

/**
 * Best-effort dual-script name fill. One Wikidata label batch plus, when needed,
 * a VIAF cluster fetch so native-script headings (`bo`, `zh`, `ja`, …) are not
 * dropped in favour of the Latin catalogue form LINCS returns. Mutates in place.
 */
export async function enrichCandidateNames(
  candidates: DisambiguationCandidate[],
  projectLang: string | null | undefined,
  fetchImpl?: WikidataFetchFn,
  kind?: EntityKind | null,
): Promise<void> {
  if (!projectLang) return;

  const needy = candidates.filter((c) => !c.projectLangName || !c.romanizedName);
  const qidsOf = (candidate: DisambiguationCandidate): string[] => [
    ...new Set([
      ...extractWikidataIdsFromText(candidate.uri),
      ...extractWikidataIdsFromText(candidate.description),
      ...(candidate.authorityIds ?? [])
        .filter((auth) => /^wikidata$/i.test(auth.type))
        .flatMap((auth) => extractWikidataIdsFromText(auth.value)),
    ]),
  ];

  let labelsByQid = new Map<string, Record<string, string>>();
  const allQids = [...new Set(needy.flatMap(qidsOf))];
  if (allQids.length > 0) {
    try {
      labelsByQid = await wikidataLabelsByQid(allQids, fetchImpl);
    } catch {
      // offline / API failure: fall through to VIAF / autogeneration
    }
  }

  const viafFetch: ViafFetchFn = (url, init) =>
    fetchImpl ? (fetchImpl as ViafFetchFn)(url, init) : fetch(url, init);
  const viafIds = [
    ...new Set(
      needy
        .filter((candidate) => !candidate.projectLangName)
        .flatMap((candidate) => viafIdsOnCandidate(candidate)),
    ),
  ];
  const viafNativeById = new Map<string, string | null>();
  if (viafIds.length > 0) {
    await Promise.all(
      viafIds.map(async (id) => {
        const heading = await viafNativeHeadingForId(id, projectLang, viafFetch);
        viafNativeById.set(id, heading);
      }),
    );
  }

  for (const candidate of needy) {
    const originalLabel = candidate.label;
    const labels: Record<string, string> = {};
    for (const qid of qidsOf(candidate)) Object.assign(labels, labelsByQid.get(qid) ?? {});

    const viafNative = viafIdsOnCandidate(candidate)
      .map((id) => viafNativeById.get(id))
      .find((heading): heading is string => Boolean(heading));

    candidate.projectLangName ??=
      preferredLabelForLang(labels, projectLang) ??
      viafNative ??
      (!isLatinSurface(candidate.label) ? candidate.label : undefined);

    if (!candidate.romanizedName) {
      const scriptName = candidate.projectLangName ?? candidate.label;
      const generated = autoRomanizeForKind(scriptName, projectLang, kind) ?? undefined;
      const strippedLatin = originalLabel
        .replace(/,?\s*\d{3,4}\s*[-–]\s*(?:\d{3,4})?\s*$/u, '')
        .replace(/,/g, '')
        .trim();
      const latinOriginal = isLatinSurface(strippedLatin) ? strippedLatin : undefined;
      if (isTibetanLanguageCode(projectLang)) {
        candidate.romanizedName = generated ?? latinOriginal;
      } else {
        const enLabel = labels['en'];
        candidate.romanizedName =
          latinOriginal ?? (enLabel && isLatinSurface(enLabel) ? enLabel : undefined) ?? generated;
      }
    }

    if (
      candidate.projectLangName &&
      textMatchesProjectScript(candidate.projectLangName, projectLang) &&
      candidate.label !== candidate.projectLangName
    ) {
      candidate.label = candidate.projectLangName;
    }
  }
}

/** Normalize a pack row's typed-name entries; unrecognized categories fall back to `variant`. */
/**
 * Typed names from a pack row's `names[]`, for ingestion as *additional*
 * name elements (courtesy, art, posthumous, …). The primary/canonical entry
 * (CBDB's `c_name_chn`, typed "primary") is deliberately excluded — it's
 * already conveyed via `primaryName`/`projectLangName`, and re-adding it here
 * would risk a second `type="primary"` name element if normalization ever
 * puts it a character apart from the chosen canonical text.
 */
export function typedNamesFromPackRow(
  names: { text: string; type?: string; lang?: string }[] | undefined,
): TypedName[] | undefined {
  if (!names?.length) return undefined;
  const raw: TypedName[] = [];
  for (const name of names) {
    const text = name.text?.trim();
    if (!text) continue;
    const type = normalizeNameType(name.type) ?? 'variant';
    if (type === 'primary') continue;
    raw.push({ text, type, lang: name.lang });
  }
  const out = normalizeTypedNamesForIntake(raw);
  return out.length ? out : undefined;
}

/**
 * All typed names the chosen authority knows for a candidate: pack-provided
 * entries plus live Wikidata name-property claims (courtesy 字, posthumous
 * 諡號, …). Called at link time — one candidate, session-cached — and
 * best-effort: network failure returns whatever the packs had.
 */
export async function collectTypedNamesForCandidate(
  candidate: DisambiguationCandidate,
  fetchImpl?: typeof fetch,
): Promise<TypedName[]> {
  const byText = new Map<string, TypedName>();
  for (const name of candidate.typedNames ?? []) {
    byText.set(name.text.normalize('NFC'), name);
  }

  const qids = wikidataQidsForCandidate(candidate);
  if (qids.length > 0) {
    try {
      const byQid = await fetchWikidataTypedNames(qids, fetchImpl);
      for (const names of byQid.values()) {
        for (const name of names) {
          const key = name.text.normalize('NFC');
          if (!byText.has(key)) byText.set(key, name);
        }
      }
    } catch {
      // best-effort — pack names (if any) still apply
    }
  }

  const familyNames = [...byText.values()]
    .filter((name) => name.type === 'family')
    .map((name) => name.text);
  return normalizeTypedNamesForIntake([...byText.values()], familyNames);
}

/** Wikidata Q-ids a candidate is linked to (its URI, description, and Wikidata authority ids). */
function wikidataQidsForCandidate(candidate: DisambiguationCandidate): string[] {
  return [
    ...new Set([
      ...extractWikidataIdsFromText(candidate.uri),
      ...extractWikidataIdsFromText(candidate.description),
      ...(candidate.authorityIds ?? [])
        .filter((auth) => /^wikidata$/i.test(auth.type))
        .flatMap((auth) => extractWikidataIdsFromText(auth.value)),
    ]),
  ];
}

/**
 * Given/family name Wikidata knows for a candidate (P735/P734 — both point at
 * a Wikidata item for the name, resolved to a label). Best-effort: network
 * failure returns an empty result rather than throwing.
 */
export async function collectGivenFamilyNamesForCandidate(
  candidate: DisambiguationCandidate,
  projectLang?: string | null,
  fetchImpl?: typeof fetch,
): Promise<WikidataGivenFamilyNames> {
  const qids = wikidataQidsForCandidate(candidate);
  if (qids.length === 0) return {};
  try {
    const byQid = await fetchWikidataGivenFamilyNames(qids, projectLang, fetchImpl);
    for (const names of byQid.values()) {
      if (names.givenName || names.familyName) return names;
    }
  } catch {
    // best-effort
  }
  return {};
}

/** Non-Latin projects get deterministic project-script labels when rows merge. */
const mergeOptionsForLang = (projectLang?: string | null): MergeCandidateOptions | undefined =>
  isEastAsianCalendarLanguageCode(projectLang) || isTibetanLanguageCode(projectLang)
    ? { preferNonLatinLabel: true }
    : undefined;

export interface BuildDisambiguationCandidatesOptions {
  /** Wikidata lifespan enrichment for live hits (default true). */
  enrichLifespans?: boolean;
  /** Fill dual-script names via Wikidata (default true). */
  enrichNames?: boolean;
  /** Called once pack/local rows are ready, before live authorities finish. */
  onPartialResults?: (candidates: DisambiguationCandidate[]) => void;
}

export async function buildDisambiguationCandidates(
  entitiesDoc: Document | null,
  tag: string,
  surface: string,
  cache: AuthorityCache,
  enabledAuthorities: (keyof typeof AUTHORITY_MAP)[] = ['Wikidata', 'VIAF'],
  forceRefresh = false,
  readPackFile?: ReadAuthorityPackFile,
  dilaDetailCache?: DilaPlaceDetailCache,
  dilaFetchImpl?: DilaFetchFn,
  onDilaDatesReady?: () => void,
  projectLang?: string | null,
  /** Present only for a syncToCentral project - merges in matching CEDB entities. */
  central?: {
    doc?: Document;
    userStableId: string;
    /** Precomputed CEDB matches (already excluding PEDB-linked ids). */
    candidates?: DisambiguationCandidate[];
  },
  /** Proximity radius (km) for collapsing place candidates into geo clusters — see Phase 6. */
  placeProximityKm?: number,
  /** Precomputed PEDB matches; when set, `entitiesDoc` is not scanned. */
  localCandidates?: DisambiguationCandidate[],
  buildOptions?: BuildDisambiguationCandidatesOptions,
): Promise<DisambiguationCandidate[]> {
  const local =
    localCandidates ?? (entitiesDoc ? candidatesFromEntityFile(entitiesDoc, tag, surface) : []);
  const centralCandidates = central
    ? (central.candidates ??
      (() => {
        if (!central.doc || !entitiesDoc) return [];
        const linked = linkedCentralIds(entitiesDoc, central.userStableId);
        return candidatesFromEntityFile(central.doc, tag, surface, 'cedb').filter(
          (candidate) => !linked.has(candidate.centralEntityId!),
        );
      })())
    : [];
  const liveOptions: FetchLiveCandidatesOptions = {
    enrichLifespans: buildOptions?.enrichLifespans,
  };
  const packPromise = readPackFile
    ? candidatesFromAuthorityPacks(
        tag,
        surface,
        readPackFile,
        dilaDetailCache,
        dilaFetchImpl,
        onDilaDatesReady,
        projectLang,
      )
    : Promise.resolve([] as DisambiguationCandidate[]);
  // Start live fetch immediately so it overlaps pack reads.
  const livePromise = fetchLiveCandidates(
    tag,
    surface,
    cache,
    enabledAuthorities,
    forceRefresh,
    readPackFile,
    liveOptions,
  );

  const mergeOpts: MergeCandidateOptions = {
    ...mergeOptionsForLang(projectLang),
    tag,
    placeProximityKm,
  };
  const concordancePromise = readPackFile
    ? loadViafWikidataConcordance(readPackFile)
    : Promise.resolve(null);
  const bdrcConcordancePromise = readPackFile
    ? loadBdrcWikidataConcordance(readPackFile)
    : Promise.resolve(null);

  const finalize = async (
    packLocal: DisambiguationCandidate[],
    live: DisambiguationCandidate[],
  ) => {
    const index = (await concordancePromise) ?? null;
    let bdrcIndex = (await bdrcConcordancePromise) ?? emptyBdrcWikidataIndex();
    const merged = mergeCandidates([local, centralCandidates, packLocal, live], mergeOpts).map(
      enrichCandidateCrossRefs,
    );
    const viafEnriched = index
      ? enrichCandidatesWithViafWikidataConcordance(merged, index)
      : merged;
    const missing = qidsMissingBdrcLink(viafEnriched, bdrcIndex);
    if (missing.length > 0) {
      try {
        bdrcIndex = mergeBdrcWikidataIndexes(bdrcIndex, await fetchBdrcIdsForQids(missing));
      } catch {
        // Pack/concordance ids still apply when Wikidata is unreachable.
      }
    }
    const enriched = enrichCandidatesWithBdrcWikidataConcordance(viafEnriched, bdrcIndex);
    return collapseCrossAuthorityCandidates(enriched, mergeOpts);
  };

  const packLocal = await packPromise;
  if (buildOptions?.onPartialResults) {
    buildOptions.onPartialResults(await finalize(packLocal, []));
  }

  const live = await livePromise;
  const merged = await finalize(packLocal, live);
  if (buildOptions?.enrichNames !== false) {
    const kind = tag === 'name' ? 'person' : TAG_TO_KIND[tag];
    await enrichCandidateNames(merged, projectLang, undefined, kind ?? null);
  }
  return merged;
}

/** Map raw per-authority candidates into the shape SQLite enrich expects. */
export function toAuthoritySourcedFields(
  candidates: DisambiguationCandidate[] | undefined,
): AuthoritySourcedFields[] | undefined {
  if (!candidates?.length) return undefined;
  const mapped = candidates
    .map((candidate): AuthoritySourcedFields => {
      const source = (
        candidate.authoritySource ??
        candidate.authorityIds?.[0]?.type ??
        candidate.sources[0] ??
        'authority'
      ).toUpperCase();
      const meta = candidate.authorityMetadata;
      const metaBioYears = meta ? biographicalYearsFromMetadata(meta) : {};
      const metaFloruitYears = meta ? floruitYearsFromMetadata(meta) : {};
      // A candidate's authorityMetadata may carry only ancillary data (e.g.
      // nationality) with no date fields of its own — fall back to the
      // candidate's own startYear/endYear rather than treating "meta present"
      // as "meta is authoritative for dates".
      const hasMetaYears =
        metaBioYears.startYear != null ||
        metaBioYears.endYear != null ||
        metaFloruitYears.startYear != null ||
        metaFloruitYears.endYear != null;
      const fallbackYears = isFilterOnlyDateSource(candidate.dateSource)
        ? {}
        : candidate.dateSource === 'floruit'
          ? {}
          : {
              ...(candidate.startYear != null ? { startYear: candidate.startYear } : {}),
              ...(candidate.endYear != null ? { endYear: candidate.endYear } : {}),
            };
      const fallbackFloruitYears =
        candidate.dateSource === 'floruit'
          ? {
              ...(candidate.startYear != null ? { startYear: candidate.startYear } : {}),
              ...(candidate.endYear != null ? { endYear: candidate.endYear } : {}),
            }
          : {};
      const bioYears = hasMetaYears ? metaBioYears : fallbackYears;
      const floruitYears = hasMetaYears ? metaFloruitYears : fallbackFloruitYears;
      const asFloruit = Boolean(floruitYears.startYear != null || floruitYears.endYear != null);
      const years = asFloruit ? floruitYears : bioYears;
      return {
        source,
        startYear: years.startYear,
        endYear: years.endYear,
        ...(asFloruit ? { asFloruit: true } : {}),
        nationality: meta?.nationality?.map((value) => ({
          canonicalId: value.canonicalId,
          label: value.label,
        })),
        origin: meta?.origin,
        description:
          candidate.dateSource === 'index'
            ? scrubIndexYearFloruitClue(candidate.description)
            : candidate.description,
      };
    })
    .filter(
      (assertion) =>
        assertion.startYear != null ||
        assertion.endYear != null ||
        assertion.nationality?.length ||
        assertion.origin?.length ||
        assertion.description,
    );
  return mapped.length ? mapped : undefined;
}

/**
 * A CEDB-origin candidate (from a syncToCentral project's merged disambiguation
 * search) must be adopted into the PEDB first — this mints/reuses a linked
 * project mirror and rewrites the candidate to look like an ordinary local
 * match (`localEntityId` set, `centralEntityId` cleared). Candidates without a
 * `centralEntityId` pass through unchanged.
 */
export async function resolveCandidateForPedb(
  candidate: DisambiguationCandidate,
  projectStore: EntityStore,
  centralStore: EntityStore,
  userStableId: string,
): Promise<DisambiguationCandidate> {
  if (!candidate.centralEntityId) return candidate;
  const adopted = await adoptFromCentralSqlite(
    projectStore,
    centralStore,
    candidate.centralEntityId,
    userStableId,
  );
  if (!adopted) throw new Error(`adopt: central entity not found: ${candidate.centralEntityId}`);
  return { ...candidate, localEntityId: adopted.pedbId, centralEntityId: undefined };
}
