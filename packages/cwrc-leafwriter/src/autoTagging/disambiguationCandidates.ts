/** External links for a candidate row (Wikidata item, VIAF cluster, etc.). */
export function candidateLinks(
  candidate: DisambiguationCandidate,
  _options: CandidateLinkOptions = {},
): CandidateLink[] {
  const links: CandidateLink[] = [];
  const seen = new Set<string>();

  const add = (kind: CandidateLink['kind'], url: string, title: string) => {
    if (seen.has(url)) return;
    seen.add(url);
    links.push({ kind, url, title });
  };

  const scan = (text: string | undefined) => {
    if (!text) return;
    const qid = extractWikidataId(text);
    if (qid) {
      add('wikidata', WIKIDATA_ITEM_URL(qid), `Wikidata (${qid})`);
    }
    const viaf = extractViafId(text);
    if (viaf) add('viaf', `https://viaf.org/viaf/${viaf}`, `VIAF ${viaf}`);
    const cbdb = extractCbdbId(text);
    if (cbdb) add('cbdb', CBDB_PERSON_URL(cbdb), `CBDB ${cbdb}`);
    const bdrc = extractBdrcId(text);
    if (bdrc) add('bdrc', BDRC_SHOW_URL(bdrc), `BDRC ${bdrc}`);
  };

  scan(candidate.uri);
  scan(candidate.description);
  for (const auth of candidate.authorityIds ?? []) {
    if (auth.type === 'CBDB') {
      add('cbdb', CBDB_PERSON_URL(auth.value), `CBDB ${auth.value}`);
    }
    if (auth.type === 'DILA') {
      add('dila', DILA_URL(auth.value), `DILA ${auth.value}`);
    }
    if (auth.type.toLowerCase() === 'bdrc') {
      const bdrc = normalizeBdrcId(auth.value);
      if (bdrc) add('bdrc', BDRC_SHOW_URL(bdrc), `BDRC ${bdrc}`);
    }
    scan(auth.value);
  }

  return links;
}

/** Project-script name when we have one; otherwise the authority's own label. */
export function candidatePrimaryLabel(candidate: DisambiguationCandidate): string {
  const script = candidate.projectLangName?.trim();
  if (script && !isLatinSurface(script)) return script;
  return candidate.label;
}

/**
 * Transliteration on its own line only when the row has no description and no
 * dates — those already occupy the subtitle. Used so Tibetan Wylie sits under
 * the uchen label instead of competing as a second primary.
 */
export function candidateRomanizationSubtitle(
  candidate: DisambiguationCandidate,
): string | undefined {
  if (candidate.description?.trim()) return undefined;
  if (candidate.startYear != null || candidate.endYear != null) return undefined;
  const romanized = candidate.romanizedName?.trim();
  if (!romanized) return undefined;
  if (romanized === candidatePrimaryLabel(candidate)) return undefined;
  return romanized;
}

function authorityKeysForCandidate(candidate: DisambiguationCandidate): string[] {
  const keys = new Set<string>();
  const scan = (text: string | undefined) => {
    if (!text) return;
    const wd = normalizeWikidataQid(text) ?? extractWikidataId(text);
    if (wd) keys.add(`wikidata:${wd}`);
    const viaf = normalizeViafId(text) ?? extractViafId(text);
    if (viaf) keys.add(`viaf:${viaf}`);
    const cbdb = extractCbdbId(text);
    if (cbdb) keys.add(`cbdb:${cbdb}`);
    const bdrc = extractBdrcId(text);
    if (bdrc) keys.add(`bdrc:${bdrc}`);
  };

  scan(candidate.uri);
  scan(candidate.description);
  scan(candidate.label);
  for (const auth of candidate.authorityIds ?? []) {
    scan(auth.value);
    const type = auth.type.trim().toLowerCase();
    const value = auth.value.trim();
    if (!value) continue;
    if (type.includes('wikidata')) {
      const wd = normalizeWikidataQid(auth.value) ?? extractWikidataId(auth.value);
      if (wd) keys.add(`wikidata:${wd}`);
    }
    if (type === 'viaf') {
      const viaf = normalizeViafId(auth.value) ?? extractViafId(auth.value);
      if (viaf) keys.add(`viaf:${viaf}`);
    }
    // Case-insensitive so PEDB idnos (NORBERT/CBDB) collapse with pack rows.
    if (type === 'cbdb') keys.add(`cbdb:${value}`);
    if (type === 'dila') keys.add(`dila:${value}`);
    if (type === 'bdrc') {
      const bdrc = normalizeBdrcId(value);
      if (bdrc) keys.add(`bdrc:${bdrc}`);
    }
    if (type === 'norbert') {
      keys.add(`norbert:${value}`);
      // Typed (`office-4135`) and bare (`4135`) forms must collapse for the
      // same kind during the migration window.
      const kindPrefixed = value.match(/^(person|office|place)[-:](.+)$/i);
      if (kindPrefixed) {
        keys.add(`norbert:${kindPrefixed[2]}`);
        keys.add(`norbert:${kindPrefixed[1]!.toLowerCase()}-${kindPrefixed[2]}`);
      }
    }
  }
  return [...keys];
}

function dedupeAuthorityIds(ids: AuthorityId[]): AuthorityId[] {
  const seen = new Set<string>();
  return ids.filter((id) => {
    const key = `${id.type}\0${id.value}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

/** Pull cross-authority ids embedded in reconcile description text. */
export function enrichCandidateCrossRefs(
  candidate: DisambiguationCandidate,
): DisambiguationCandidate {
  const authorityIds = dedupeAuthorityIds(
    authorityIdsFromCrossRefs(candidate.authorityIds ?? [], candidate.description, candidate.uri),
  );
  return { ...candidate, authorityIds };
}

function authorityIdsFromCrossRefs(
  base: AuthorityId[],
  ...texts: (string | undefined)[]
): AuthorityId[] {
  const out = [...base];
  const seen = new Set(out.map((id) => `${id.type}\0${id.value}`));
  const add = (type: AuthorityId['type'], value: string) => {
    const key = `${type}\0${value}`;
    if (seen.has(key)) return;
    seen.add(key);
    out.push({ type, value });
  };
  for (const text of texts) {
    if (!text) continue;
    const wikidata = text.match(/wikidata\.org\/(?:wiki|entity)\/(Q\d+)/i)?.[1]?.toUpperCase();
    if (wikidata) add('Wikidata', wikidata);

    const viaf = text.match(/viaf\.org\/(?:[a-z]{2}\/)?viaf\/(\d+)/i)?.[1];
    if (viaf) add('VIAF', viaf);

    const cbdb = extractCbdbId(text);
    if (cbdb) add('CBDB', cbdb);

    const dila = text.match(
      /authority\.dila\.edu\.tw\/[^\s]*?(?:aid=|fromInner=|code=|\/)([A-Z]{1,2}\d+)/,
    )?.[1];
    if (dila) add('DILA', dila);

    const ndl = text.match(/id\.ndl\.go\.jp\/auth\/(?:ndlna|ndlsh)\/([\w-]+)/i)?.[1];
    if (ndl) add('NDL', ndl);

    const bdrc = extractBdrcId(text);
    if (bdrc) add('BDRC', bdrc);
  }
  return out;
}

export interface MergeCandidateOptions {
  /**
   * Deterministic label for non-Latin projects: prefer a project-script label
   * over whichever row happens to come first (pack rows can surface a
   * romanized or Korean label for a Chinese person, depending on which
   * search string matched).
   */
  preferNonLatinLabel?: boolean;
  /** The mention group's tag — geo-cluster merging only applies to `'placeName'`. */
  tag?: string;
  /**
   * Radius (km) within which two place candidates are treated as the same
   * functional location and collapsed into one row (see
   * docs/placename-geo-disambiguation-planning.md, Phase 6). Only takes
   * effect when `tag === 'placeName'`.
   */
  placeProximityKm?: number;
}

/** Merge checked rows into one candidate (manual link or accept). */
export function mergeSelectedCandidates(
  candidates: DisambiguationCandidate[],
  options?: MergeCandidateOptions,
): DisambiguationCandidate | null {
  if (candidates.length === 0) return null;
  const first = candidates[0]!;
  const fromFile = candidates.find((c) => c.fromEntityFile);
  const projectLangName = candidates.map((c) => c.projectLangName).find(Boolean);
  const romanizedName = candidates.map((c) => c.romanizedName).find(Boolean);
  const typedByText = new Map<string, TypedName>();
  for (const candidate of candidates) {
    for (const name of candidate.typedNames ?? []) {
      const key = name.text.normalize('NFC');
      if (!typedByText.has(key)) typedByText.set(key, name);
    }
  }
  const normalizedTypedNames = normalizeTypedNamesForIntake([...typedByText.values()]);
  const typedNames = normalizedTypedNames.length ? normalizedTypedNames : undefined;
  const nonLatinLabel = options?.preferNonLatinLabel
    ? (candidates.map((c) => c.label).find((label) => label && !isLatinSurface(label)) ??
      candidates.map((c) => c.projectLangName).find((name) => name && !isLatinSurface(name)) ??
      projectLangName)
    : undefined;
  const authorityAssertionMap = new Map<string, DisambiguationCandidate>();
  for (const candidate of candidates.flatMap((candidate) => {
    if (candidate.authorityAssertions?.length) return candidate.authorityAssertions;
    if (candidate.fromEntityFile || candidate.localEntityId || candidate.centralEntityId) return [];
    return [candidate];
  })) {
    const key = `${candidate.uri ?? candidate.id}\0${candidate.sources.join(',')}`;
    authorityAssertionMap.set(key, candidate);
  }
  const authorityAssertions = [...authorityAssertionMap.values()];
  const bioBearing = candidates.filter(
    (c) => !isFilterOnlyDateSource(c.dateSource) && (c.startYear != null || c.endYear != null),
  );
  const yearSources = bioBearing.length ? bioBearing : candidates;
  const startYears = yearSources.map((c) => c.startYear).filter((y): y is number => y != null);
  const endYears = yearSources.map((c) => c.endYear).filter((y): y is number => y != null);
  const filterOnly = candidates.find((c) => isFilterOnlyDateSource(c.dateSource));
  const dateSource = bioBearing.length
    ? (bioBearing.find((c) => c.dateSource === 'fine')?.dateSource ?? undefined)
    : filterOnly?.dateSource;
  return {
    id: fromFile?.id ?? first.id,
    label: fromFile?.label ?? nonLatinLabel ?? first.label,
    projectLangName,
    romanizedName,
    typedNames,
    description:
      [...new Set(candidates.map((c) => c.description).filter(Boolean))].join(' · ') ||
      first.description,
    sources: [...new Set(candidates.flatMap((c) => c.sources))],
    uri: fromFile?.uri ?? first.uri,
    localEntityId: fromFile?.localEntityId ?? first.localEntityId,
    centralEntityId: fromFile?.centralEntityId ?? first.centralEntityId,
    fromEntityFile: candidates.some((c) => c.fromEntityFile),
    authorityIds: dedupeAuthorityIds(candidates.flatMap((c) => c.authorityIds ?? [])),
    startYear: startYears.length ? Math.min(...startYears) : undefined,
    endYear: endYears.length ? Math.max(...endYears) : undefined,
    dateSource,
    dynasty: candidates.find((c) => c.dynasty)?.dynasty,
    geo: mergedGeo(candidates),
    authorityMetadata:
      candidates.find((c) => c.authorityMetadata)?.authorityMetadata ?? first.authorityMetadata,
    authorityAssertions: authorityAssertions.length ? authorityAssertions : undefined,
  };
}

/**
 * Representative point for a merged row: the centroid of every source
 * candidate that carries coordinates. A single geo-bearing candidate's
 * centroid is just that point, so this subsumes the old first-wins
 * behavior for non-place merges while giving places (Phase 6) the "mean of
 * the cluster" point the disambiguation-panel map needs.
 */
function mergedGeo(
  candidates: DisambiguationCandidate[],
): { lat: number; lon: number } | undefined {
  const points = candidates
    .map((c) => c.geo)
    .filter((geo): geo is { lat: number; lon: number } => geo != null);
  return points.length > 0 ? centroidOf(points) : undefined;
}

/** Collapse rows that share a Wikidata Q-id or other cross-authority key. */
export function collapseCrossAuthorityCandidates(
  candidates: DisambiguationCandidate[],
  options?: MergeCandidateOptions,
): DisambiguationCandidate[] {
  if (candidates.length < 2) return candidates;

  const parent = candidates.map((_, index) => index);
  const find = (index: number): number =>
    parent[index] === index ? index : (parent[index] = find(parent[index]!));
  const union = (a: number, b: number) => {
    parent[find(a)] = find(b);
  };

  const keyToIndices = new Map<string, number[]>();
  candidates.forEach((candidate, index) => {
    for (const key of authorityKeysForCandidate(candidate)) {
      const list = keyToIndices.get(key) ?? [];
      list.push(index);
      keyToIndices.set(key, list);
    }
  });

  for (const indices of keyToIndices.values()) {
    const head = indices[0]!;
    for (let i = 1; i < indices.length; i++) union(head, indices[i]!);
  }

  // Different authorities agreeing on the exact same birth and death years is
  // itself a strong enough signal to treat two rows as the same person, even
  // without a shared cross-referenced id.
  for (let i = 0; i < candidates.length; i++) {
    for (let j = i + 1; j < candidates.length; j++) {
      if (find(i) === find(j)) continue;
      const a = candidates[i]!;
      const b = candidates[j]!;
      const sameAuthority = a.sources.some((source) => b.sources.includes(source));
      if (sameAuthority) continue;
      if (a.startYear == null || a.endYear == null) continue;
      if (a.startYear !== b.startYear || a.endYear !== b.endYear) continue;
      union(i, j);
    }
  }

  // Place candidates within the configured proximity radius are treated as
  // the same functional location (docs/placename-geo-disambiguation-planning.md,
  // Phase 6) — same union-find, so it composes with the id/year passes above
  // rather than replacing them. Candidates missing coordinates never merge on
  // this pass (mirrors authorityOverlap.ts's shouldMergePlacePackCandidates).
  if (options?.tag === 'placeName' && options?.placeProximityKm != null) {
    for (let i = 0; i < candidates.length; i++) {
      for (let j = i + 1; j < candidates.length; j++) {
        if (find(i) === find(j)) continue;
        const a = candidates[i]!;
        const b = candidates[j]!;
        if (!a.geo || !b.geo) continue;
        if (haversineDistanceKm(a.geo, b.geo) > options.placeProximityKm) continue;
        union(i, j);
      }
    }
  }

  const groups = new Map<number, DisambiguationCandidate[]>();
  candidates.forEach((candidate, index) => {
    const root = find(index);
    const list = groups.get(root) ?? [];
    list.push(candidate);
    groups.set(root, list);
  });

  return [...groups.values()].map((group) => mergeSelectedCandidates(group, options)!);
}

