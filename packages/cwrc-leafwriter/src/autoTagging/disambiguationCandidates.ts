export interface DisambiguationCandidate {
  id: string;
  label: string;
  description?: string;
  sources: string[];
  uri?: string;
  authorityIds?: AuthorityId[];
  authoritySource?: string;
  localEntityId?: string;
  /**
   * Set instead of `localEntityId` when this candidate comes from the
   * central database (syncToCentral) rather than this project's own PEDB.
   * Resolving it requires adopting a PEDB mirror first - see
   * `resolveCandidateForPedb`. When the project is synced, linked CEDB hits
   * are rewritten to carry `localEntityId` instead so accept/document checks
   * work without showing a Local vs Central split.
   */
  centralEntityId?: string;
  fromEntityFile?: boolean;
  /**
   * Years used by the Disambiguate date filter and (for places/offices / real floruit) captions.
   * For persons these may be birth/death, floruit earliest–latest, or CBDB index filter windows
   * — see {@link dateSource}. Index years are never minted or shown as `fl.`
   */
  startYear?: number;
  /** Death/dissolution year, or end of a floruit/filter/period interval. */
  endYear?: number;
  /**
   * Pack `metadata.dateSource`. `floruit` = real fl. earliest/latest; `index`/`nationality`
   * = filter anchors only (never shown/stored as floruit).
   */
  dateSource?: 'fine' | 'floruit' | 'index' | 'nationality';
  /** DILA place records are split one-per-dynasty (e.g. 東晉); kept for a future dynasty filter/picker. */
  dynasty?: string;
  /** Entity's full name in the project source language script (authority-provided). */
  projectLangName?: string;
  /** Latin-script name: authority-provided (pinyin/yomi/en label) or autogenerated. */
  romanizedName?: string;
  /** Typed names from the authority (courtesy/posthumous/…), ingested into entities.xml on linking. */
  typedNames?: TypedName[];
  /** WGS84 coordinates, when the source authority carries them (CHGIS, CBDB places). */
  geo?: { lat: number; lon: number };
  /** Raw pack metadata needed when the selected office is minted. */
  authorityMetadata?: AuthorityCandidate['metadata'];
  /** Raw authority rows retained when a display candidate is deduplicated. */
  authorityAssertions?: DisambiguationCandidate[];
}

/** Accept only WGS84 coordinates; CHGIS also contains projected layer values. */
export function normalizeGeo(
  geo: { lat: number; lon: number } | undefined,
): { lat: number; lon: number } | undefined {
  if (!geo || !Number.isFinite(geo.lat) || !Number.isFinite(geo.lon)) return undefined;
  if (geo.lat < -90 || geo.lat > 90 || geo.lon < -180 || geo.lon > 180) return undefined;
  return geo;
}

